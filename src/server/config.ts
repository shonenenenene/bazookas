// Настройки игрового сервера.

export const SERVER = {
  /**
   * Порт: и сама игра (собранная, из dist/), и WebSocket (/ws), и список комнат (/api/rooms).
   * В разработке Vite пересылает на него /ws и /api (см. vite.config.ts).
   * Переменная окружения PORT важнее — так порт задают хостинги и Docker
   */
  port: Number(process.env.PORT) || 8080,
  /** Снимок мира рассылается каждые столько тиков: 2 → 30 раз в секунду */
  snapshotEvery: 2,
  /** Живых игроков в одной комнате */
  maxPlayers: 10,
  /** Комнат на сервере одновременно (защита от того, кто наплодит их тысячу) */
  maxRooms: 50,
  /** Соединений с одного адреса (IP) — защита от «одного человека с сотней вкладок» */
  maxConnectionsPerIp: 6,
  /**
   * Сервер стоит за прокси (Nginx Proxy Manager, nginx): адрес игрока брать из заголовка X-Forwarded-For.
   * Без прокси поставь TRUST_PROXY=0 — иначе заголовок можно подделать
   */
  trustProxy: process.env.TRUST_PROXY !== '0',
  /** Раз в столько секунд проверяем, жив ли игрок (см. «пульс» в main.ts). Мёртвого выкидываем через 1–2 таких интервала */
  heartbeat: 10,

  /** Матч «каждый сам за себя» (match.ts) */
  match: {
    fragLimit: 25, //    до скольких фрагов
    timeLimit: 600, //   или сколько секунд (10 минут)
    intermission: 10, // пауза с итогами перед следующим матчем, секунд
  },

  // Защита от «ускорялок»: клиент не может прислать больше команд, чем идёт тиков
  /** Сколько команд разом можно применить после подвисания клиента (запас «на догонку») */
  maxCmdBurst: 10,
  /** Если в очереди копится больше команд — старые выбрасываем, иначе задержка так и останется */
  maxCmdQueue: 4,
};

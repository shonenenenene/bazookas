// Настройки игрового сервера.

export const SERVER = {
  /**
   * Порт WebSocket-сервера. В разработке Vite пересылает на него адрес /ws (см. vite.config.ts).
   * Переменная окружения PORT важнее — так порт задают хостинги
   */
  port: Number(process.env.PORT) || 8080,
  /** Снимок мира рассылается каждые столько тиков: 2 → 30 раз в секунду */
  snapshotEvery: 2,
  /** Живых игроков в одной комнате */
  maxPlayers: 12,
  /** Ставить в комнаты манекенов с карты — чтобы было в кого стрелять, пока друзья не зашли */
  dummies: true,
  /** Раз в столько секунд проверяем, жив ли игрок (см. «пульс» в main.ts). Мёртвого выкидываем через 1–2 таких интервала */
  heartbeat: 10,

  // Защита от «ускорялок»: клиент не может прислать больше команд, чем идёт тиков
  /** Сколько команд разом можно применить после подвисания клиента (запас «на догонку») */
  maxCmdBurst: 10,
  /** Если в очереди копится больше команд — старые выбрасываем, иначе задержка так и останется */
  maxCmdQueue: 4,
};
